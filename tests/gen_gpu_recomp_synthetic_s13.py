#!/usr/bin/env python3
"""RE24-S13: synthetic JRISC program (no ROM data) for the recompiler test.
Writes OUT.bin (4 KiB GPU RAM image at $F03000) and OUT.c (generated by
tools/jagref/gpu_recomp.py).  usage: gen_gpu_recomp_synthetic_s13.py OUT"""
import os,struct,sys
sys.dont_write_bytecode=True
sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','tools','jagref'))
import gpu_recomp
B=0xF03000;img=bytearray(4096);at=B
def w(x):
    global at;img[at-B:at-B+2]=struct.pack('>H',x&0xFFFF);at+=2
def I(op,r1,r2):w((op<<10)|((r1&31)<<5)|(r2&31))
def movei(v,r):I(38,0,r);w(v);w(v>>16)
END=0xF03FF0
movei(0x12345678,1);movei(0x0000FFFF,2);I(35,7,3);movei(37,10);movei(0xF03800,14)
movei(0x9ABCDEF0,4);movei(0x80000001,5);movei(0,6);movei(0x7FFF,9);movei(0xF03400,15)
loop=at;movei(loop,20)
I(0,1,2)        # add r1,r2
I(11,2,1)       # xor r2,r1
I(29,5,1)       # rorq #5,r1
I(17,3,2)       # imult r3,r2
I(1,3,4)        # addc r3,r4
I(27,3,2)       # sharq #3,r2
I(21,3,1)       # div r3,r1
I(2,3,3)        # addq #3,r3
I(47,14,2)      # store r2,(r14)
I(2,4,14)       # addq #4,r14
I(34,2,5)       # move r2,r5
I(33,0,5)       # sat16 r5
I(0,5,6)        # add r5,r6
I(5,4,6)        # subc r4,r6
I(18,9,4)       # imultn r9,r4
I(20,9,5)       # imacn r9,r5
I(19,0,7)       # resmac r7
I(23,3,4)       # sh r3,r4
I(26,10,5)      # sha r10,r5
I(28,3,6)       # ror r3,r6
I(13,4,6)       # btst #4,r6
I(53,2,1)       # jr eq,+2
I(57,0,0)       # nop (slot)
I(14,9,8)       # bset #9,r8
I(30,4,5)       # cmp r4,r5
I(31,-3&31,6)   # cmpq #-3,r6
I(6,1,10)       # subq #1,r10
I(52,20,1)      # jump ne,(r20)
I(36,6,11)      # moveta r6,r11 (delay slot)
I(37,11,12)     # movefa r11,r12
I(43,2,13)      # load (r14+2),r13
I(22,0,5)       # abs r5
I(8,0,4)        # neg r4
I(32,0,4)       # sat8 r4
I(16,1,2)       # mult r1,r2
I(41,15,16)     # load (r15),r16
I(40,15,17)     # loadw (r15),r17
I(39,15,18)     # loadb (r15),r18
I(46,15,6)      # storew r6,(r15)
I(45,15,7)      # storeb r7,(r15)
I(50,3,4)       # store r4,(r15+3)
I(51,0,19)      # move pc,r19
movei(END,21);I(52,21,0);I(57,0,0)   # jump (r21) leaves the routine
hi=at
out=sys.argv[1]
open(out+'.bin','wb').write(img)
open(out+'.c','w').write(gpu_recomp.emit(img,B,[(B,hi)],'synthetic_recomp',(),'from a synthetic test program')+'\n')
