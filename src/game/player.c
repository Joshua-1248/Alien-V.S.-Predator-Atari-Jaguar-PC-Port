/* PLAYER.S::HumanPain.  random is deliberately called before hugkill is
 * tested: the assembly consumes the RNG value even on the forced facehugger
 * scream path. */
void HumanPain(void)
{
    u32 r=avp_random();
    if(hugkill || (r&7u)>5u){
        pain_sfx((r&1u)?AVP_SFX_HUMAN_AAGH_A:AVP_SFX_HUMAN_AAGH_B);
        return;
    }
    switch((r&7u)>>1){
    case 0: pain_sfx(AVP_SFX_HUMAN_UHH_A); break;
    case 1: pain_sfx(AVP_SFX_HUMAN_UHH_B); break;
    default:pain_sfx(AVP_SFX_HUMAN_UHH_C); break;
    }
}

void Pain(void)
{
    s32 p=(s16)pain;
    s16 delta=0;

    if(player_energy>0){
        delta=(s16)(old_energy-player_energy);
        old_energy=player_energy;
    }

    if(player_energy>0 && delta>0){
        /* Source performs the sound decision before adding MIN_PAIN. */
        if((u32)(frame_counter-last_moan)>10u){
            u32 r;
            last_moan=frame_counter;
            if(player_type==PT_HUMAN){
                /* The original random draw must occur even when muted. */
                if(pc_player_pain_sounds_enabled && (!hugkill||pc_facehug_pain_sounds_enabled))HumanPain();
                else (void)avp_random();
            }else if(player_type==PT_ALIEN){
                r=avp_random()&3u;
                if(pc_player_pain_sounds_enabled && (!hugkill||pc_facehug_pain_sounds_enabled))pain_sfx(alien_pain_fx[r]);
            }else{
                r=avp_random()&3u;
                if(pc_player_pain_sounds_enabled && (!hugkill||pc_facehug_pain_sounds_enabled))pain_sfx(predator_pain_fx[r]);
            }
        }
        p+=(s32)delta+50; /* MIN_PAIN */
    }else{
        p-=20;            /* RECOVERY_RATE */
    }

    if(p<=0){
        pain=0;
        fade_c=0x8880u;
        return;
    }
    if(p>=100)p=99;      /* MAX_PAIN-1 */
    pain=(s16)p;

    /* PAIN_MUL = ($10000*16)/100; MULU then SWAP is floor(p*16/100). */
    {
        unsigned idx=(unsigned)(((u32)(u16)p*16u)/100u);
        if(idx>15u)idx=15u;
        if(!destruct_flag)
            fade_c=pain_lists[player_type==PT_ALIEN?1:player_type==PT_PREDATOR?2:0][idx];
    }
}



/* PLAYER.S TestSpark/shoot_loop.  This keeps the retail 68000 ordering:
 * random angular spread, gun-swing adjustment, CPU FireDistance wall trace,
 * coarse shot box, signed low-word rotation, closest-z selection, damage flags
 * and the deliberately 7/8-positioned Human spark. */
static s32 spark_x,spark_y;
static AvpPlayerMpShotHook player_mp_shot_hook;
static void *player_mp_shot_user;
void avp_player_set_mp_shot_hook(AvpPlayerMpShotHook callback,void *user)
{player_mp_shot_hook=callback;player_mp_shot_user=callback?user:NULL;}
static u32 shot_distance;

static s32 abs_s32_local(s32 v){return v<0?(s32)(-(s64)v):v;}

AvpAmp *TestSpark(void)
{
    AvpAmp *best=NULL;
    u32 closest=0xffffffffu;
    s32 best_offset=0;
    s32 shotx,shoty;
    s16 cs,sn;
    u32 trace_dist;
    s32 boxx,boxy;
    if(!wep_fire)return NULL;

    /* random leaves its 16-bit result in d0.w; SWAP/ASR #7 is equivalent to
     * sign-extending that word and shifting it left nine places. */
    {
        /* Original 68000 ADD/SUB are modulo 32 bits.  A negative d0.w
         * must not be left-shifted as a signed C value (undefined behavior).
         * Signed 16-bit spread * 512 fits s32; unsigned ADD/SUB then exactly
         * preserves the Jaguar register's 32-bit wraparound. */
        u32 a=centre_angle+(u32)((s32)(s16)avp_random()*512);
        /* The surviving retail source literally tests the code label
         * `enable_swing`, not swing_on.  The first opcode byte is non-zero in
         * the retail routine, so the swing term is always taken. Preserve the
         * executable behavior rather than silently correcting the source typo. */
        a-=(u32)((s64)(s16)swing_x*0x400000ll);
        fire_angle=a;
    }

    {
        u16 a=(u16)(fire_angle>>16);
        cs=(s16)cos_d0(a);
        sn=(s16)(-sin_d0(a));
    }

    shot_distance=FireDistance();
    trace_dist=shot_distance?shot_distance:fire_distance;
    {
        s16 dw=(s16)(trace_dist>>8);
        shotx=((s32)cs*(s32)dw)>>7;
        shoty=((s32)sn*(s32)dw)>>7;
    }
    spark_x=shotx;spark_y=shoty;
    /* PLAYER.S widens the signed fire-width word before *512.  Signed
     * multiplication is defined for every s16 width; left-shifting a
     * negative signed value was undefined C behavior. */
    boxx=abs_s32_local(shotx)+(s32)(s16)fire_width*512;
    boxy=abs_s32_local(shoty)+(s32)(s16)fire_width*512;

    for(unsigned i=0;i<AVP_NUM_AMPS;i++) {
        AvpAmp *a=&amps_at[i];
        s32 dx,dy,adx,ady,rx,ry,z,xoff;
        u32 uz;
        if((!a->mode&&!a->host_static)||!(a->flags&(1u<<AMP_KILLABLE)))continue;
        dx=a->xpos-(s32)x_pos;dy=a->ypos-(s32)y_pos;
        adx=abs_s32_local(dx);ady=abs_s32_local(dy);
        if((u32)adx>=(u32)boxx||(u32)ady>=(u32)boxy)continue;

        rx=dx>>8;ry=dy>>8;
        z=(s32)((s32)(s16)ry*(s32)sn)+(s32)((s32)(s16)rx*(s32)cs);
        if(z<0)continue;
        uz=(u32)z;if(uz>=closest)continue;
        xoff=(s32)((s32)(s16)rx*(s32)sn)-(s32)((s32)(s16)ry*(s32)cs);
        if((u32)(abs_s32_local(xoff)>>16)>(u32)(u16)fire_width)continue;
        closest=uz;best=a;best_offset=xoff;
    }

    /* Optional local Deathmatch player avatars. Original AMP hit-selection
     * and random spread are already complete; leave them untouched. */
    if(player_mp_shot_hook && player_mp_shot_hook(player_mp_shot_user,
           (s32)x_pos,(s32)y_pos,boxx,boxy,cs,sn,fire_width,
           closest,fire_damage))return NULL;

    if(best) {
        s32 dx=best->xpos-(s32)x_pos,dy=best->ypos-(s32)y_pos;
        s16 off=(s16)(best_offset>>16);
        s32 corrx=((s32)off*(s32)sn)>>7;
        s32 corry=((s32)off*(s32)cs)>>7;
        dx-=corrx;dy+=corry;
        best->energy=(s16)(best->energy-fire_damage);
        /* PLAYER.S:1064-1067: OR invisflag in -- "once set, stays set". */
        best->flags|=(u16)((1u<<AMP_PHIT)|(1u<<AMP_CLOSEHIT)|invisflag);
        if(player_type==PT_HUMAN) {
            dx-=dx>>3;dy-=dy>>3;
            make_spark_hit_at((s32)x_pos+dx,(s32)y_pos+dy,best);
        }
        return best;
    }

    if(player_type==PT_HUMAN && shot_distance) {
        s32 dx=spark_x,dy=spark_y;
        dx-=dx>>3;dy-=dy>>3;
        make_spark_at((s32)x_pos+dx,(s32)y_pos+dy,0);
    }
    return NULL;
}

void TidyMove(void) {
    u32 ax=(x_vel<0)?(u32)(-(s64)x_vel):(u32)x_vel;
    u32 ay=(y_vel<0)?(u32)(-(s64)y_vel):(u32)y_vel;
    u32 small=ax,large=ay;
    if (large<small) { u32 t=large; large=small; small=t; }
    player_vel=(u16)(large+(small>>2));
    u16 av=(u16)(ang_vel<0 ? -ang_vel : ang_vel);
    av=(u16)(av<<2);
    if (player_vel<=av) player_vel=av;

    old_pos=new_pos;
    /* Source indexes MAZE_DATA by high words of 16.16 world coordinates and
     * uses maze_width cells per row, each cell 8 bytes.  In the 68000 source,
     * `maze_width+2` is an address displacement selecting the low word of the
     * 32-bit `maze_width` variable; it does NOT mean width plus two.  The public C
     * decomp stores the byte offset instead of a host pointer. */
    u32 gx=x_pos>>16, gy=y_pos>>16;
    new_pos=((gy*(u32)maze_width)+gx)<<MAZE_BLOCK_SHIFT;
}


